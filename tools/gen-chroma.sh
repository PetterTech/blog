#!/usr/bin/env bash
# Regenerate assets/css/chroma.css – the syntax-highlighting colours for code blocks – from Hugo's built-in
# Chroma styles (preview: https://gohugo.io/quick-reference/syntax-highlighting-styles/).
#   bash tools/gen-chroma.sh [dark-style] [light-style]      (default: github-dark github)
# Token rules are scoped to :root[data-theme=dark|light] so they follow the theme toggle. Backgrounds, line
# numbers and line highlighting are left out: code block colours/backgrounds come from site.css (--code-*).
# "Error" tokens (e.g. curly quotes and en dashes that WordPress put into old code) are left unstyled too.
set -euo pipefail
cd "$(dirname "$0")/.."
HUGO="${HUGO:-hugo}"
DARK="${1:-github-dark}"
LIGHT="${2:-github}"
OUT=assets/css/chroma.css
skip='^\.chroma \.(err|lnlinks|lntd|lntable|hl|lnt|ln|line|cl) '
{
  echo "/* Generated by tools/gen-chroma.sh: $DARK (dark) and $LIGHT (light). Do not edit by hand. */"
  "$HUGO" gen chromastyles --style="$DARK" --omitClassComments | grep -E '^\.chroma \.' | grep -Ev "$skip" | sed 's/^/:root[data-theme="dark"] /'
  "$HUGO" gen chromastyles --style="$LIGHT" --omitClassComments | grep -E '^\.chroma \.' | grep -Ev "$skip" | sed 's/^/:root[data-theme="light"] /'
} > "$OUT"
echo "wrote $OUT ($(wc -l < "$OUT") lines)"
